import { describe, expect, it } from "vitest";
import { addWorkdays, isWorkday, workdaysBetween } from "@/lib/workdays";

// DS-01 · Рабочие дни и срок готовности заявки (SPEC §6.5 п.6, AC-5.7). Тесты готовы, их не менять.
//
// Правила (решение D-003):
// - рабочий день: пн–пт, кроме NON_WORKING_WEEKDAYS, плюс WORKING_WEEKENDS (config/holidays.ts);
// - день подачи E: московский день подачи, если он рабочий и время ≤ 17:00:00 МСК;
//   иначе (после 17:00, выходной, праздник) — следующий рабочий день;
// - срок = 18:00 МСК N-го рабочего дня после E (сам E не считается): справка за 1 день,
//   поданная в четверг утром, готова в пятницу к 18:00;
// - ответ — ISODateTime с явным смещением +03:00;
// - workdaysBetween(a, b): число рабочих дней d, для которых день(a) < d ≤ день(b), по Москве.
//   При b раньше a — то же число со знаком минус. Нужен для «Срок прошёл на 1 день».

describe("isWorkday", () => {
  it.each([
    ["2026-11-12", true, "чт"],
    ["2026-11-14", false, "сб"],
    ["2026-11-15", false, "вс"],
    ["2026-11-03", true, "вт, предпраздничный сокращённый — рабочий"],
    ["2026-11-04", false, "ср, День народного единства"],
    ["2026-01-09", false, "пт, перенос с 3 января"],
    ["2026-03-09", false, "пн, перенос 8 марта"],
    ["2026-05-11", false, "пн, перенос 9 мая"],
    ["2026-12-31", false, "чт, перенос с 4 января"],
    ["2027-01-01", false, "Новый год"],
    ["2027-01-08", false, "пт, каникулы"],
    ["2027-01-11", true, "пн, первый рабочий день 2027"],
    ["2027-02-20", true, "сб, рабочая суббота"],
    ["2027-02-22", false, "пн, перенос с 20 февраля"],
    ["2027-11-05", false, "пт, перенос с 2 января"],
  ])("%s → %s (%s)", (date, expected) => {
    expect(isWorkday(date)).toBe(expected);
  });
});

describe("addWorkdays: срок готовности", () => {
  it("будний день утром: 1 рабочий день → завтра в 18:00 МСК", () => {
    expect(addWorkdays("2026-11-12T10:00:00+03:00", 1)).toBe("2026-11-13T18:00:00+03:00");
  });

  it("пятница: срок переходит через выходные на понедельник", () => {
    expect(addWorkdays("2026-11-13T10:00:00+03:00", 1)).toBe("2026-11-16T18:00:00+03:00");
  });

  it("ровно 17:00 — ещё день подачи, 17:01 — уже следующий рабочий день", () => {
    expect(addWorkdays("2026-11-13T17:00:00+03:00", 1)).toBe("2026-11-16T18:00:00+03:00");
    expect(addWorkdays("2026-11-13T17:01:00+03:00", 1)).toBe("2026-11-17T18:00:00+03:00");
  });

  it("поданная в выходной считается поданной в понедельник", () => {
    expect(addWorkdays("2026-11-14T12:00:00+03:00", 1)).toBe("2026-11-17T18:00:00+03:00");
    expect(addWorkdays("2026-11-15T09:00:00+03:00", 2)).toBe("2026-11-18T18:00:00+03:00");
  });

  it("предпраздничный день: праздник 4 ноября пропускается", () => {
    expect(addWorkdays("2026-11-03T10:00:00+03:00", 1)).toBe("2026-11-05T18:00:00+03:00");
    expect(addWorkdays("2026-11-02T10:00:00+03:00", 2)).toBe("2026-11-05T18:00:00+03:00");
  });

  it("поданная в сам праздник считается поданной в следующий рабочий день", () => {
    expect(addWorkdays("2026-11-04T11:00:00+03:00", 1)).toBe("2026-11-06T18:00:00+03:00");
  });

  it("Новый год: 31 декабря и каникулы 1–10 января пропускаются", () => {
    expect(addWorkdays("2026-12-30T10:00:00+03:00", 1)).toBe("2027-01-11T18:00:00+03:00");
    expect(addWorkdays("2026-12-30T18:00:00+03:00", 1)).toBe("2027-01-12T18:00:00+03:00");
    expect(addWorkdays("2026-12-29T10:00:00+03:00", 5)).toBe("2027-01-14T18:00:00+03:00");
  });

  it("рабочая суббота 20.02.2027 считается, перенесённый понедельник — нет", () => {
    expect(addWorkdays("2027-02-19T10:00:00+03:00", 1)).toBe("2027-02-20T18:00:00+03:00");
    expect(addWorkdays("2027-02-20T10:00:00+03:00", 1)).toBe("2027-02-24T18:00:00+03:00");
  });

  it("выписка оценок за 5 рабочих дней", () => {
    expect(addWorkdays("2026-11-12T10:00:00+03:00", 5)).toBe("2026-11-19T18:00:00+03:00");
  });

  it("время на входе в UTC переводится в Москву до сравнения с 17:00", () => {
    // 13:30Z = 16:30 МСК — ещё день подачи; 14:30Z = 17:30 МСК — уже нет.
    expect(addWorkdays("2026-11-12T13:30:00Z", 1)).toBe("2026-11-13T18:00:00+03:00");
    expect(addWorkdays("2026-11-12T14:30:00Z", 1)).toBe("2026-11-16T18:00:00+03:00");
    // 21:30Z четверга = 00:30 МСК пятницы: день подачи — пятница.
    expect(addWorkdays("2026-11-12T21:30:00Z", 1)).toBe("2026-11-16T18:00:00+03:00");
  });
});

describe("workdaysBetween", () => {
  it("в пределах одного дня — 0", () => {
    expect(workdaysBetween("2026-11-12T10:00:00+03:00", "2026-11-12T18:00:00+03:00")).toBe(0);
  });

  it("срок в пятницу, сейчас понедельник — просрочка на 1 рабочий день", () => {
    expect(workdaysBetween("2026-11-13T18:00:00+03:00", "2026-11-16T10:00:00+03:00")).toBe(1);
  });

  it("неделя: 5 рабочих дней, выходные не считаются", () => {
    expect(workdaysBetween("2026-11-12T18:00:00+03:00", "2026-11-19T18:00:00+03:00")).toBe(5);
  });

  it("праздник не считается", () => {
    expect(workdaysBetween("2026-11-03T18:00:00+03:00", "2026-11-05T10:00:00+03:00")).toBe(1);
    expect(workdaysBetween("2026-12-30T18:00:00+03:00", "2027-01-11T09:00:00+03:00")).toBe(1);
  });

  it("b раньше a — отрицательное число", () => {
    expect(workdaysBetween("2026-11-16T10:00:00+03:00", "2026-11-13T18:00:00+03:00")).toBe(-1);
  });

  it("согласован с addWorkdays: от рабочего утра до срока ровно N рабочих дней", () => {
    for (const from of [
      "2026-11-12T10:00:00+03:00",
      "2026-11-03T09:00:00+03:00",
      "2026-12-29T12:00:00+03:00",
      "2027-02-19T16:59:00+03:00",
    ]) {
      for (const n of [1, 2, 3, 5, 10]) {
        expect(workdaysBetween(from, addWorkdays(from, n)), `${from} + ${n}`).toBe(n);
      }
    }
  });
});
